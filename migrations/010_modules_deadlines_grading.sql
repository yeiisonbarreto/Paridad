CREATE TABLE modules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_-]{0,31}$'),
    title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120)
);

INSERT INTO modules (code, title) SELECT code, title FROM activities;

ALTER TABLE activities
    ADD COLUMN module_id bigint REFERENCES modules(id),
    ADD COLUMN opens_at timestamptz,
    ADD COLUMN closes_at timestamptz,
    ADD CONSTRAINT activities_valid_window CHECK (opens_at < closes_at);
UPDATE activities a SET module_id = m.id FROM modules m WHERE a.code = m.code;
ALTER TABLE activities ALTER COLUMN module_id SET NOT NULL;
CREATE INDEX activities_module_idx ON activities(module_id, code);

ALTER TABLE submissions
    DROP COLUMN automatic_grade,
    ADD COLUMN similarity_penalty smallint GENERATED ALWAYS AS
        (round(30 * max_similarity_bp / 10000.0)::smallint) STORED,
    ADD COLUMN automatic_grade smallint GENERATED ALWAYS AS
        (CASE WHEN quality_points IS NOT NULL THEN
            greatest(0, quality_points + 15 - round(30 * max_similarity_bp / 10000.0)::smallint)
        END) STORED;

DROP INDEX submissions_rubric_pending_idx;
CREATE INDEX submissions_rubric_pending_idx ON submissions(created_at, id)
    WHERE state = 'completed' AND (rubric @> '{"version": 2}') IS NOT TRUE;
